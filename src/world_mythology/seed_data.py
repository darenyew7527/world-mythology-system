def _source(
    source_id: str,
    title: str,
    source_type: str,
    tier: int,
    url: str | None,
    institution: str,
    *,
    author: str | None = None,
    language_id: str | None = None,
    catalogue_number: str | None = None,
    manuscript_number: str | None = None,
    rights_status: str | None = None,
    notes: str | None = None,
    perspective: str | None = None,
    community: str | None = None,
    collector_context: str | None = None,
    living: bool = False,
    restrictions: str | None = None,
    community_permission: bool = False,
    same_witness: str | None = None,
    translation_status: str | None = None,
    verification_receipt: dict | None = None,
) -> dict:
    if verification_receipt:
        receipt = json.dumps(verification_receipt, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
        notes = f"{notes}\nVERIFICATION_RECEIPT_JSON={receipt}" if notes else f"VERIFICATION_RECEIPT_JSON={receipt}"
    return {
        "id": source_id,
        "title": title,
        "source_type": source_type,
        "evidence_tier": tier,
        "institution": institution,
        "author_or_editor": author,
        "language_id": language_id,
        "accessed_date": ACCESSED_DATE,
        "url": url,
        "catalogue_number": catalogue_number,
        "manuscript_number": manuscript_number,
        "rights_status": rights_status,
        # A URL is only syntax-valid at seed time. WEB_CONFIRMED requires a
        # machine-readable verification receipt retained in notes.
        "verification_status": "WEB_CONFIRMED" if verification_receipt else ("URL_SYNTAX_VALID" if url else "REGISTERED"),
        "notes": notes,
        "source_perspective": perspective,
        "community_or_lineage": community,
        "collector_context": collector_context,
        "living_tradition": int(living),
        "access_or_reuse_restrictions": restrictions,
        "community_permission_required": int(community_permission),
        "same_witness_as_source_id": same_witness,
        "translation_status": translation_status,
    }


