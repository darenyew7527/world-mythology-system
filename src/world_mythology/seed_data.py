def _relationship_claim(
    claim_id: str,
    subject: str,
    predicate: str,
    obj: str,
    statement: str,
    *,
    source_id: str | None = None,
    source_location: str | None = None,
    evidence_type: str = "ANCIENT_TEXT",
    confidence: float = 0.8,
    review_status: str = "VERIFIED",
    claim_status: str = "SUPPORTED",
    assertion_scope: str = "IN_TRADITION",
    knowledge_layer: str = "MYTHIC_NARRATIVE",
    variant_group: str | None = None,
    notes: str | None = None,
    evidence_strength: float | None = None,
) -> dict:
    return {
        "id": claim_id,
        "subject_id": subject,
        "predicate": predicate,
        "object_entity_id": obj,
        "object_literal": None,
        "statement": statement,
        "claim_status": claim_status,
        "confidence": confidence,
        "confidence_level": "HIGH" if confidence >= 0.8 else "MEDIUM" if confidence >= 0.55 else "LOW",
        "review_status": review_status,
        "assertion_scope": assertion_scope,
        "knowledge_layer": knowledge_layer,
        "variant_group": variant_group,
        "research_notes": notes,
        "source_id": source_id,
        "source_location": source_location,
        "evidence_type": evidence_type,
        "evidence_strength": evidence_strength if evidence_strength is not None else confidence,
    }


