const titleCase = (value) =>
  value
    .toLowerCase()
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ')

export const typeLabel = (value, language) =>
  language === 'zh' ? TYPE_ZH[value] ?? value : titleCase(value)

export const relationLabel = (value, language) =>
  language === 'zh' ? RELATION_ZH[value] ?? value : titleCase(value)

export const statusLabel = (value, language) =>
  language === 'zh' ? STATUS_ZH[value] ?? value : titleCase(value)

export const entityDisplay = (entity, language) => {
  if (!entity) return ''
  if (language === 'zh') return entity.nameZh || entity.canonicalName
  return entity.canonicalName || entity.nameZh
}

export const entitySecondary = (entity, language) => {
  if (!entity) return ''
  if (language === 'zh') return entity.canonicalName === entity.nameZh ? '' : entity.canonicalName
  return entity.nameZh === entity.canonicalName ? '' : entity.nameZh
}

export const civilizationDisplay = (entity, language) =>
  language === 'zh'
    ? entity.civilizationNameZh || entity.civilizationName || '—'
    : entity.civilizationName || entity.civilizationNameZh || '—'
